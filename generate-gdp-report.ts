function generateReport(): void {
  const sorted2025 = [...gdpData.provinces]
    .sort((a, b) => (b.years["2025"] || 0) - (a.years["2025"] || 0));

  console.log("\n" + "=".repeat(70));
  console.log("  📊 全国各省 GDP 数据报告（2017-2025）");
  console.log("=".repeat(70));
  console.log(`  数据来源: 国家统计局 data.stats.gov.cn`);
  console.log(`  指标: 地区生产总值（亿元）`);
  console.log(`  省份数: ${gdpData.provinces.length} 个`);
  console.log("=".repeat(70));

  console.log("\n📈 2025 年 GDP 排名:\n");
  sorted2025.forEach((p, i) => {
    const gdp = p.years["2025"];
    const prevGdp = p.years["2024"];
    const growth = prevGdp ? ((gdp - prevGdp) / prevGdp * 100).toFixed(1) : "N/A";
    const bar = "█".repeat(Math.round(gdp / 5000));
    console.log(`  ${(i + 1).toString().padStart(2)}. ${p.province.padEnd(10)} ${gdp?.toLocaleString().padStart(10)} 亿元  增长: ${growth}%  ${bar}`);
  });

  // 计算总计
  const total2025 = gdpData.provinces.reduce((s, p) => s + (p.years["2025"] || 0), 0);
  const total2024 = gdpData.provinces.reduce((s, p) => s + (p.years["2024"] || 0), 0);
  const totalGrowth = ((total2025 - total2024) / total2024 * 100).toFixed(1);

  console.log("\n" + "-".repeat(70));
  console.log(`  合计: ${total2025.toLocaleString()} 亿元 (2025年)`);
  console.log(`  同比增长: ${totalGrowth}%`);
  console.log("-".repeat(70));

  // 区域分析
  const regions: Record<string, string[]> = {
    "东部": ["北京市", "天津市", "河北省", "上海市", "江苏省", "浙江省", "福建省", "山东省", "广东省", "海南省"],
    "中部": ["山西省", "安徽省", "江西省", "河南省", "湖北省", "湖南省"],
    "西部": ["内蒙古自治区", "广西壮族自治区", "重庆市", "四川省", "贵州省", "云南省", "西藏自治区", "陕西省", "甘肃省", "青海省", "宁夏回族自治区", "新疆维吾尔自治区"],
    "东北": ["辽宁省", "吉林省", "黑龙江省"]
  };

  console.log("\n🗺️  区域 GDP 分析（2025年）:\n");
  for (const [region, provs] of Object.entries(regions)) {
    const regionTotal = provs.reduce((s, name) => {
      const found = gdpData.provinces.find(p => p.province === name);
      return s + (found?.years["2025"] || 0);
    }, 0);
    const pct = (regionTotal / total2025 * 100).toFixed(1);
    console.log(`  ${region}地区: ${regionTotal.toLocaleString().padStart(12)} 亿元  占比 ${pct}%`);
  }

  console.log("\n" + "=".repeat(70));
}

generateReport();
